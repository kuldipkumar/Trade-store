#!/usr/bin/env python3
"""Sync docs/02-backlog.md to GitHub Issues (one issue per user story).

docs/02-backlog.md is the source of truth. Issues are generated from it, never edited
by hand. Re-running the script is idempotent: it creates missing labels, milestones and
issues, and updates the body, labels and milestone of existing ones. It never changes
an issue's open/closed state.

Usage:
    python3 scripts/sync_backlog_issues.py --dry-run   # show what would change
    python3 scripts/sync_backlog_issues.py             # apply

Requires the GitHub CLI (`gh`), authenticated with access to the repository.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

BACKLOG = Path(__file__).resolve().parent.parent / "docs" / "02-backlog.md"
BACKLOG_PATH_IN_REPO = "docs/02-backlog.md"
GENERATED_MARKER = "<!-- generated by scripts/sync_backlog_issues.py; edit docs/02-backlog.md instead -->"

PRIORITY = {"M": "Must", "S": "Should", "C": "Could"}

MILESTONES = {
    3: ("Phase 3: High-level design", "Context, container and deployment diagrams; ADRs agreed."),
    4: ("Phase 4: Walking skeleton and CI/CD", "Pipeline green: build, diagrams, test, scan, coverage gate."),
    5: ("Phase 5: Low-level design", "Every story maps to classes and a sequence flow."),
    6: ("Phase 6: TDD implementation", "Red, Green, Refactor per story; pipeline green."),
    7: ("Phase 7: Integration and regression", "End-to-end flows pass in CI with Testcontainers."),
    8: ("Phase 8: Documentation", "Someone new can clone, run and understand it in 10 minutes."),
}

# Which phase delivers each story (from "Suggested delivery order" in the backlog).
STORY_PHASE = {
    "US-601": 4, "US-602": 4, "US-606": 4,
    "US-603": 7, "US-605": 7,
    "US-608": 8, "US-609": 8,
}
DEFAULT_STORY_PHASE = 6

# Phase-gate tracking issues (gate text from AGENTS.md section 2).
PHASE_GATES = {
    3: "Components, technology choices and ADRs agreed; diagrams render. Must satisfy PO constraint CR-6 (no lost audit entries).",
    4: "Pipeline green: build, diagrams, test, scan and coverage gate all running.",
    5: "Every story maps to classes and a sequence flow.",
    6: "Red, Green, Refactor followed for every story; pipeline green.",
    7: "End-to-end flows pass in CI (Testcontainers).",
    8: "Someone new can clone, run and understand the project in 10 minutes.",
}

DEFINITION_OF_DONE = """### Definition of Done (AGENTS.md section 10)
- [ ] Acceptance criteria covered by tests written before the code
- [ ] All tests green locally and in CI
- [ ] Coverage gate passed
- [ ] No critical or blocker vulnerabilities
- [ ] PlantUML diagrams created or updated in the same commit, and rendering in CI
- [ ] Docs updated if the design changed
- [ ] Prompt(s) logged in `PROMPTS.md`"""


@dataclass
class Story:
    story_id: str
    title: str
    priority: str  # M / S / C
    epic_id: str
    epic_name: str
    heading: str
    body: str

    @property
    def issue_title(self) -> str:
        return f"{self.story_id}: {self.title}"

    @property
    def phase(self) -> int:
        return STORY_PHASE.get(self.story_id, DEFAULT_STORY_PHASE)


def gh(*args: str, check: bool = True) -> str:
    result = subprocess.run(["gh", *args], capture_output=True, text=True)
    if check and result.returncode != 0:
        sys.exit(f"gh {' '.join(args)} failed:\n{result.stderr}")
    return result.stdout


def github_anchor(heading: str) -> str:
    anchor = heading.strip().lower()
    anchor = re.sub(r"[^\w\- ]", "", anchor)
    return anchor.replace(" ", "-")


def parse_backlog(text: str) -> list[Story]:
    stories: list[Story] = []
    epic_id = epic_name = ""
    current: dict | None = None

    def flush():
        if current:
            body = "\n".join(current["lines"]).strip().rstrip("-").strip()
            stories.append(Story(body=body, **{k: v for k, v in current.items() if k != "lines"}))

    for line in text.splitlines():
        epic = re.match(r"^## (E\d+): (.+)$", line)
        story = re.match(r"^### (US-\d+): (.+) \(([MSC])\)$", line)
        if epic or story or line.startswith("## "):
            flush()
            current = None
        if epic:
            epic_id, epic_name = epic.group(1), epic.group(2).strip()
        elif story:
            current = {
                "story_id": story.group(1),
                "title": story.group(2).strip(),
                "priority": story.group(3),
                "epic_id": epic_id,
                "epic_name": epic_name,
                "heading": line[4:],
                "lines": [],
            }
        elif current is not None:
            current["lines"].append(line)
    flush()
    return stories


def story_body(story: Story, repo: str) -> str:
    link = f"https://github.com/{repo}/blob/main/{BACKLOG_PATH_IN_REPO}#{github_anchor(story.heading)}"
    return "\n\n".join([
        GENERATED_MARKER,
        f"**Epic:** {story.epic_id} {story.epic_name} · **Priority:** {PRIORITY[story.priority]} · "
        f"**Source:** [{BACKLOG_PATH_IN_REPO}]({link})",
        story.body,
        DEFINITION_OF_DONE,
    ])


def gate_body(phase: int) -> str:
    return "\n\n".join([
        GENERATED_MARKER,
        f"Tracks the gate for **{MILESTONES[phase][0]}** (AGENTS.md section 2).",
        f"**Gate:** {PHASE_GATES[phase]}",
        "Close this issue when the human approves the phase.",
    ])


def labels_for(story: Story) -> list[str]:
    return ["type:story", f"epic:{story.epic_id}", f"priority:{PRIORITY[story.priority].lower()}"]


def ensure_labels(stories: list[Story], dry_run: bool) -> None:
    wanted = {
        "type:story": ("1d76db", "User story from docs/02-backlog.md"),
        "type:phase-gate": ("5319e7", "SDLC phase gate (AGENTS.md section 2)"),
        "priority:must": ("b60205", "MoSCoW: Must"),
        "priority:should": ("fbca04", "MoSCoW: Should"),
        "priority:could": ("c2e0c6", "MoSCoW: Could"),
    }
    for s in stories:
        wanted[f"epic:{s.epic_id}"] = ("0e8a16", f"{s.epic_id}: {s.epic_name}")
    existing = {l["name"] for l in json.loads(gh("label", "list", "--limit", "200", "--json", "name"))}
    for name, (color, desc) in wanted.items():
        if name in existing:
            continue
        print(f"label   + {name}")
        if not dry_run:
            gh("label", "create", name, "--color", color, "--description", desc)


def ensure_milestones(repo: str, dry_run: bool) -> None:
    existing = {m["title"] for m in json.loads(gh("api", f"repos/{repo}/milestones?state=all&per_page=100"))}
    for title, desc in MILESTONES.values():
        if title in existing:
            continue
        print(f"mstone  + {title}")
        if not dry_run:
            gh("api", f"repos/{repo}/milestones", "-f", f"title={title}", "-f", f"description={desc}")


def existing_issues() -> dict[str, dict]:
    issues = json.loads(gh("issue", "list", "--state", "all", "--limit", "500",
                           "--json", "number,title,body,labels,milestone"))
    by_key = {}
    for issue in issues:
        key = issue["title"].split(":", 1)[0].strip()
        by_key[key] = issue
    return by_key


def upsert(key: str, title: str, body: str, labels: list[str], milestone: str,
           current: dict | None, dry_run: bool) -> None:
    if current is None:
        print(f"issue   + {title}")
        if not dry_run:
            gh("issue", "create", "--title", title, "--body", body,
               "--label", ",".join(labels), "--milestone", milestone)
        return
    current_labels = {l["name"] for l in current["labels"]}
    current_milestone = (current.get("milestone") or {}).get("title")
    if (current["title"] == title and current["body"].strip() == body.strip()
            and set(labels) <= current_labels and current_milestone == milestone):
        return
    print(f"issue   ~ #{current['number']} {title}")
    if not dry_run:
        args = ["issue", "edit", str(current["number"]), "--title", title, "--body", body,
                "--add-label", ",".join(labels), "--milestone", milestone]
        gh(*args)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true", help="print planned changes without applying them")
    args = parser.parse_args()

    stories = parse_backlog(BACKLOG.read_text(encoding="utf-8"))
    if not stories:
        sys.exit("No stories parsed from the backlog.")
    ids = [s.story_id for s in stories]
    if len(ids) != len(set(ids)):
        sys.exit("Duplicate story IDs in the backlog.")

    repo = json.loads(gh("repo", "view", "--json", "nameWithOwner"))["nameWithOwner"]
    print(f"{repo}: {len(stories)} stories, {len(PHASE_GATES)} phase gates{' (dry run)' if args.dry_run else ''}")

    ensure_labels(stories, args.dry_run)
    ensure_milestones(repo, args.dry_run)
    current = existing_issues()

    for phase in sorted(PHASE_GATES):
        key = f"Phase {phase} gate"
        title = f"{key}: {MILESTONES[phase][0].split(': ', 1)[1]}"
        upsert(key, title, gate_body(phase), ["type:phase-gate"], MILESTONES[phase][0],
               current.get(key), args.dry_run)

    for story in stories:
        upsert(story.story_id, story.issue_title, story_body(story, repo), labels_for(story),
               MILESTONES[story.phase][0], current.get(story.story_id), args.dry_run)


if __name__ == "__main__":
    main()
